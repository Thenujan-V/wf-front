// Writes src/app/core/ui/icons.ts from the lucide package (ISC licence), so the app carries only the drawings it uses
// and has no icon dependency at run time. Run after adding a name below: npm run build:icons
import { writeFileSync } from 'node:fs';
import { icons } from 'lucide';

// Our name -> lucide's name. Several candidates, because lucide renames icons between versions; the first one that
// exists is used.
const WANTED = {
  inbox: ['Inbox'],
  file: ['FileText'],
  folder: ['Folder'],
  'folder-open': ['FolderOpen'],
  chart: ['ChartColumn', 'BarChart3', 'BarChart'],
  form: ['LayoutList', 'ListChecks', 'FormInput'],
  flow: ['Workflow', 'GitBranch'],
  tag: ['Tag', 'Tags'],
  activity: ['Activity'],
  users: ['Users'],
  shield: ['ShieldCheck', 'Shield'],
  bell: ['Bell'],
  search: ['Search'],
  sun: ['Sun'],
  moon: ['Moon'],
  menu: ['Menu'],
  x: ['X'],
  clock: ['Clock'],
  check: ['Check'],
  plus: ['Plus'],
  'chevron-down': ['ChevronDown'],
  'chevron-right': ['ChevronRight'],
  'log-out': ['LogOut'],
  user: ['User', 'UserRound'],
  upload: ['Upload'],
  download: ['Download'],
  trash: ['Trash2', 'Trash'],
  refresh: ['RefreshCw', 'RotateCw'],
  alert: ['TriangleAlert', 'AlertTriangle'],
  'arrow-left': ['ArrowLeft'],
  pause: ['Pause', 'CirclePause'],
  play: ['Play', 'CirclePlay'],
  ban: ['Ban', 'CircleSlash'],
};

const out = {};
for (const [name, candidates] of Object.entries(WANTED)) {
  const found = candidates.find((candidate) => icons[candidate]);
  if (!found) {
    console.error(`No lucide icon for "${name}" (tried ${candidates.join(', ')}). Add its current name to WANTED.`);
    process.exit(1);
  }
  // A lucide icon is a list of [tag, attributes]; only the shape and its geometry are kept.
  out[name] = icons[found].map(([tag, attrs]) => {
    const { key, ...geometry } = attrs;
    return [tag, Object.fromEntries(Object.entries(geometry).map(([k, v]) => [k, String(v)]))];
  });
}

const body = Object.entries(out)
  .map(([name, nodes]) => `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`)
  .join('\n');

writeFileSync(new URL('../src/app/core/ui/icons.ts', import.meta.url), `// GENERATED by scripts/build-icons.mjs from lucide (https://lucide.dev, ISC licence). Do not edit by hand.

/** One shape of a drawing: its SVG tag and attributes. */
export type IconNode = readonly [tag: string, attributes: Readonly<Record<string, string>>];

export const ICONS = {
${body}
} as const satisfies Record<string, readonly IconNode[]>;

export type IconName = keyof typeof ICONS;
`);
console.log(`wrote ${Object.keys(out).length} icons`);
